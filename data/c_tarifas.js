// Función auxiliar: obtener tarifa por región y categoría
function obtenerTarifa(region, categoria, fecha = null) {
  const tarifas = window.TarifasData.tarifas_region.filter(t =>
    t.region_cut === region && t.segmento_categoria === categoria &&
    (!fecha || t.fecha_vigencia === fecha)
  );

  if (tarifas.length === 0) return null;

  // Retornar la más reciente si no se especifica fecha
  return tarifas[tarifas.length - 1];
}

// Función auxiliar: obtener evolución temporal de tarifa
function obtenerEvolucion(categoria, region = null) {
  let datos = window.TarifasData.tarifas_nacional.filter(t =>
    t.segmento_categoria === categoria
  );

  if (region) {
    datos = window.TarifasData.tarifas_region.filter(t =>
      t.segmento_categoria === categoria && t.region_cut === region
    );
  }

  return datos.sort((a, b) => new Date(a.fecha_vigencia) - new Date(b.fecha_vigencia));
}
